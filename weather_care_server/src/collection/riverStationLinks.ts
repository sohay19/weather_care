export function riverStationLinks(hrfcoNames: Map<string, string>, kwaterNames: Map<string, string>) {
  const normalize = (name: string) => name.replace(/[\s()（）·]/g, '');
  return new Map(verifiedLinks.filter(([kwater, hrfco, name]) =>
    normalize(hrfcoNames.get(hrfco) ?? '') === normalize(name) &&
    normalize(kwaterNames.get(kwater) ?? '') === normalize(name))
    .map(([kwater, hrfco]) => [kwater, hrfco]));
}
