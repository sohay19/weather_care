const {chromium}=require('C:/Users/SOHA/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const path=require('path');
(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:736,height:1050}});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('file:///'+path.resolve(__dirname,'nearby-weather-preview.inspect.html').replaceAll('\\','/'));
  const f=page.frameLocator('iframe');await f.locator('[data-preview="compact"]').waitFor();
  await f.locator('.source-summary').click();
  await page.waitForTimeout(150);
  if(await f.locator('.source-details').getAttribute('open')===null)throw new Error('Details missing');
  await page.screenshot({path:path.resolve(__dirname,'nearby-weather-detail.png'),fullPage:true});
  await f.locator('.source-summary').click();
  await page.waitForTimeout(150);
  await page.screenshot({path:path.resolve(__dirname,'nearby-weather-compact.png'),fullPage:true});
  console.log('buttons',await f.getByRole('button').allTextContents());
  await f.getByRole('button',{name:'다음 예시',exact:true}).click();
  if(!await f.locator('[data-preview="notice"]').isVisible())throw new Error('Carousel did not switch');
  await page.screenshot({path:path.resolve(__dirname,'nearby-weather-notice.png'),fullPage:true});
  await page.setViewportSize({width:320,height:1100});
  await page.waitForTimeout(150);
  await page.screenshot({path:path.resolve(__dirname,'nearby-weather-mobile.png'),fullPage:true});
  const frame=page.frames()[1];
  const overflow=await frame.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:path.resolve(__dirname,'nearby-weather-dark.png'),fullPage:true});
  console.log(JSON.stringify({errors,mobileOverflow:overflow}));
  if(errors.length||overflow)throw new Error('Preview failed');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
